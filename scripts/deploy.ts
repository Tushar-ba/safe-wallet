import { ethers, network, run } from "hardhat";
import { mkdirSync, writeFileSync } from "fs";
import { join } from "path";
import { CANONICAL_AMOY } from "./addresses";

// Deploys ONLY TxProposalRegistry; the canonical Safe v1.4.1 contracts already exist on Amoy and are reused.
// On the fork dry-run (FORK=1) results go to deployments/amoy.fork.json and the frontend config is NOT touched.
async function main() {
  const [deployer] = await ethers.getSigners();
  if (!deployer) throw new Error("No deployer account: set DEPLOYER_PRIVATE_KEY in .env");
  const chainId = Number((await ethers.provider.getNetwork()).chainId);
  if (chainId !== 80002) throw new Error(`Expected chainId 80002, got ${chainId}`);

  for (const [name, addr] of Object.entries(CANONICAL_AMOY)) {
    const code = await ethers.provider.getCode(addr);
    if (code === "0x") throw new Error(`${name} (${addr}) has no code on this network`);
  }

  console.log(`Deployer ${deployer.address}, balance ${ethers.formatEther(await ethers.provider.getBalance(deployer.address))} POL`);
  const registry = await ethers.deployContract("TxProposalRegistry");
  const receipt = await registry.deploymentTransaction()!.wait();
  const registryAddress = await registry.getAddress();
  console.log(`TxProposalRegistry: ${registryAddress} (block ${receipt!.blockNumber})`);

  const isFork = network.name === "hardhat";
  const out = {
    chainId,
    ...CANONICAL_AMOY,
    txProposalRegistry: registryAddress,
    registryDeployBlock: receipt!.blockNumber,
  };

  mkdirSync("deployments", { recursive: true });
  writeFileSync(join("deployments", isFork ? "amoy.fork.json" : "amoy.json"), JSON.stringify(out, null, 2) + "\n");

  if (!isFork) {
    const ts =
      `// GENERATED by scripts/deploy.ts from deployments/amoy.json - do not edit.\n` +
      `export const deployments = ${JSON.stringify(out, null, 2)} as const;\n`;
    mkdirSync("frontend/src/config", { recursive: true });
    writeFileSync("frontend/src/config/deployments.ts", ts);

    try {
      await new Promise((r) => setTimeout(r, 15000)); // let the explorer index the contract
      await run("verify:verify", { address: registryAddress, constructorArguments: [] });
    } catch (e: any) {
      console.warn("Verification failed (retry with: npx hardhat verify --network amoy " + registryAddress + "):", e.message);
    }
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
